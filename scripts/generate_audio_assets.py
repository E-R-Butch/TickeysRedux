#!/usr/bin/env python3
"""Rebuild Tickeys Redux's original synthetic packs using only Python's stdlib.

The script and its generated audio use the project's MIT license. No recordings,
sample libraries or existing WAV files are inputs to the synthesis functions.
Run --check to compare all generated bytes and the complete asset inventory.
"""

import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "assets" / "data"
RATE = 44_100
BASE_SEED = 0x5449434B
PEAK = 0.55
GENERATED = {
    "typewriter": "Synth Typewriter",
    "sword": "Synth Blades",
    "Cherry_G80_3000": "Synth Click",
    "Cherry_G80_3494": "Synth Thock",
    "starwars": "Synth Space",
}
THIRD_PARTY = {
    "bubble": ("CC-BY-3.0", "Glaneur de sons", "bubble/license.txt"),
    "drum": ("CC0-1.0", "Veiler", "drum/_readme_and_license.txt"),
    "mechanical": ("CC0-1.0", "jim-ph", "mechanical/license.txt"),
}


def seed_for(path):
    """A stable per-file seed, independent of Python's randomized hash()."""
    digest = hashlib.sha256(path.encode("utf-8")).digest()
    return BASE_SEED ^ int.from_bytes(digest[:4], "little")


def noise_stream(seed):
    """Explicit xorshift32 so the noise does not depend on random module versions."""
    state = seed or 1
    while True:
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        state &= 0xFFFFFFFF
        yield state / 2147483648.0 - 1.0


def pulse(t, frequency, decay, delay=0.0):
    t -= delay
    if t < 0:
        return 0.0
    return math.sin(math.tau * frequency * t) * math.exp(-t / decay)


def synthesize(scheme, filename, index):
    path = f"{scheme}/{filename}"
    seed = seed_for(path)
    variation = 0.94 + (seed % 1201) / 10_000
    duration = {
        "typewriter": 0.16,
        "sword": 0.21,
        "Cherry_G80_3000": 0.11,
        "Cherry_G80_3494": 0.14,
        "starwars": 0.20,
    }[scheme]
    is_enter = "enter" in filename or "return" in filename
    is_space = "space" in filename and "back" not in filename
    if scheme == "typewriter" and is_enter:
        duration = 0.40
    elif is_enter:
        duration += 0.06
    elif is_space:
        duration += 0.025
    frames = round(duration * RATE)
    noise = noise_stream(seed)
    values = []
    low_noise = 0.0
    for i in range(frames):
        t = i / RATE
        n = next(noise)
        low_noise += 0.12 * (n - low_noise)
        high_noise = n - low_noise
        if scheme == "Cherry_G80_3000":
            # A short bright down/up click, with no physical keyboard sample.
            v = 0.55 * high_noise * math.exp(-t / 0.006)
            v += 0.55 * pulse(t, 1850 * variation, 0.009)
            v += 0.30 * pulse(t, 820 * variation, 0.016)
            v += 0.30 * pulse(t, 2350 * variation, 0.008, 0.026)
        elif scheme == "Cherry_G80_3494":
            # A lower, damped body resonance with a soft return tap.
            v = 0.85 * pulse(t, 235 * variation, 0.023)
            v += 0.33 * pulse(t, 470 * variation, 0.014)
            v += 0.28 * low_noise * math.exp(-t / 0.017)
            v += 0.17 * high_noise * math.exp(-t / 0.004)
            v += 0.23 * pulse(t, 380 * variation, 0.013, 0.037)
        elif scheme == "typewriter":
            # Metallic key impact, second mechanism tap, and a return bell.
            v = 0.45 * high_noise * math.exp(-t / 0.007)
            v += 0.50 * pulse(t, 690 * variation, 0.024)
            v += 0.25 * pulse(t, 2110 * variation, 0.019)
            v += 0.28 * pulse(t, 980 * variation, 0.013, 0.039)
            if is_enter:
                v += 0.38 * pulse(t, 1568, 0.083, 0.065)
                v += 0.12 * pulse(t, 3136, 0.056, 0.065)
            elif "scroll" in filename:
                for delay in (0.025, 0.050, 0.075):
                    v += 0.25 * pulse(t, 870 * variation, 0.008, delay)
        elif scheme == "sword":
            # Noise swish and inharmonic resonances, not recorded weapon foley.
            swish = (1.0 - math.exp(-t / 0.006)) * math.exp(-t / 0.033)
            v = 0.35 * high_noise * swish
            v += 0.32 * pulse(t, 1390 * variation, 0.035)
            v += 0.22 * pulse(t, 2377 * variation, 0.028)
            v += 0.13 * pulse(t, 3551 * variation, 0.019)
        else:
            # Two generic electronic chirps. No film or franchise sound inputs.
            start = 1100 + 250 * index
            end = 340 + 90 * index
            phase = math.tau * (start * t + (end - start) * t * t / (2 * duration))
            v = math.sin(phase + 0.9 * math.sin(math.tau * 71 * t))
            v *= math.exp(-t / 0.046)
            v += 0.08 * high_noise * math.exp(-t / 0.012)
        # Short fades eliminate discontinuities at file boundaries.
        fade_in = min(1.0, i / 44)
        fade_out = min(1.0, (frames - 1 - i) / 441)
        values.append(v * fade_in * fade_out)
    # Remove DC using the same fade envelope, retaining zero-valued endpoints.
    weights = [min(1.0, i / 44) * min(1.0, (frames - 1 - i) / 441)
               for i in range(frames)]
    dc = sum(values) / sum(weights)
    values = [value - dc * weight for value, weight in zip(values, weights)]
    scale = PEAK * 32767 / max(abs(value) for value in values)
    pcm = [round(value * scale) for value in values]
    output = io.BytesIO()
    with wave.open(output, "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(RATE)
        wav.writeframes(struct.pack(f"<{len(pcm)}h", *pcm))
    return output.getvalue(), seed


def describe(path, content, scheme, seed=None):
    with wave.open(io.BytesIO(content), "rb") as wav:
        channels, width, rate, frames = (
            wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getnframes()
        )
        if width != 2 or wav.getcomptype() != "NONE":
            raise ValueError(f"Expected PCM16 WAV: {path}")
        pcm = struct.unpack(f"<{frames * channels}h", wav.readframes(frames))
    entry = {
        "path": path,
        "sha256": hashlib.sha256(content).hexdigest(),
        "channels": channels,
        "sample_rate_hz": rate,
        "frames": frames,
        "duration_seconds": round(frames / rate, 6),
        "peak_pcm16": max(abs(value) for value in pcm),
    }
    if seed is not None:
        entry.update(license="MIT", source="scripts/generate_audio_assets.py", seed=seed)
    else:
        license_id, author, notice = THIRD_PARTY[scheme]
        entry.update(license=license_id, author=author, source=notice)
    return entry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify without writing")
    args = parser.parse_args()
    schemes = json.loads((DATA / "schemes.json").read_text())
    entries = []
    mismatches = []
    generated_count = 0
    for scheme in schemes:
        name = scheme["name"]
        if name not in GENERATED and name not in THIRD_PARTY:
            raise SystemExit(f"Missing provenance policy for scheme: {name}")
        count = len(scheme["files"])
        if not 0 < scheme["non_unique_count"] <= count or any(
            not 0 <= value < count for value in scheme["key_audio_map"].values()
        ):
            raise SystemExit(f"Invalid audio mapping in scheme: {name}")
        for index, filename in enumerate(scheme["files"]):
            rel = f"{name}/{filename}"
            target = DATA / rel
            seed = None
            if name in GENERATED:
                content, seed = synthesize(name, filename, index)
                generated_count += 1
                if args.check:
                    if not target.exists() or target.read_bytes() != content:
                        mismatches.append(rel)
                else:
                    target.write_bytes(content)
            else:
                content = target.read_bytes()
            entries.append(describe(rel, content, name, seed))
    inventoried = {entry["path"] for entry in entries}
    actual = {p.relative_to(DATA).as_posix() for p in DATA.rglob("*.wav")}
    if inventoried != actual:
        raise SystemExit(f"Uninventoried or missing WAVs: {sorted(inventoried ^ actual)}")
    manifest = {
        "format_version": 1,
        "generator": "scripts/generate_audio_assets.py",
        "base_seed": BASE_SEED,
        "generated_peak_target": PEAK,
        "assets": entries,
    }
    serialized = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    path = DATA / "audio-manifest.json"
    if args.check:
        if not path.exists() or path.read_text() != serialized:
            mismatches.append(path.name)
        if mismatches:
            raise SystemExit("Audio assets differ: " + ", ".join(mismatches))
    else:
        path.write_text(serialized)
    print(f"{'Verified' if args.check else 'Generated'} {generated_count} synthetic WAVs; "
          f"inventoried {len(entries)} total WAVs.")


if __name__ == "__main__":
    main()
